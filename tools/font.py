# ---------------------------------------------------------------- accents (composés sur la lettre de base)
ACC = {
    "acute": ["...#.", "..#.."], "grave": [".#...", "..#.."], "circ": ["..#..", ".#.#."],
    "trema": [".....", ".#.#."], "ring": ["..#..", ".#.#."],
}
COMPOSE = {
    "é": ("e", "acute"), "è": ("e", "grave"), "ê": ("e", "circ"), "ë": ("e", "trema"),
    "à": ("a", "grave"), "â": ("a", "circ"), "ä": ("a", "trema"),
    "ù": ("u", "grave"), "û": ("u", "circ"), "ü": ("u", "trema"),
    "ô": ("o", "circ"), "ö": ("o", "trema"), "î": ("ı", "circ"), "ï": ("ı", "trema"),
    "É": ("E", "acute"), "È": ("E", "grave"), "Ê": ("E", "circ"), "À": ("A", "grave"), "Â": ("A", "circ"),
    "Ô": ("O", "circ"), "Î": ("I", "circ"), "Ù": ("U", "grave"), "Û": ("U", "circ"), "Ç": ("C", None),
    "ç": ("c", None),
}
CEDILLA = ["..#..", ".##.."]


def grid(ch):
    """Glyphe complet sur 11 lignes : liste de chaînes de même largeur."""
    if ch in COMPOSE:
        base, acc = COMPOSE[ch]
        body, desc = G[base]
        w = max(len(r) for r in body)
        top = [["."] * max(w, 5) for _ in range(4)]
        if acc:
            mark = ACC[acc]
            off = (len(top[0]) - 5) // 2
            caps = base.isupper()
            for i, r in enumerate(mark):
                row = i if caps else i + 2  # majuscule : lignes 0-1 ; minuscule : 2-3 (au-dessus de la hauteur d'x)
                for j, c in enumerate(r):
                    if c == "#":
                        top[row][j + off] = "#"
        W = max(w, 5)
        pad = (W - w) // 2
        rows = ["".join(r) for r in top[:2]]
        b = [("." * pad + r).ljust(W, ".") for r in body]
        if acc and not base.isupper():  # minuscule : l'accent remplace les 2 lignes vides au-dessus de la hauteur d'x
            for i in range(2):
                b[i] = "".join("#" if (top[i + 2][k] == "#" or b[i][k] == "#") else "." for k in range(W))
        if acc is None:
            desc = CEDILLA
        d = [("." * ((W - len(r)) // 2) + r).ljust(W, ".") for r in desc]
        return rows + b + d + ["." * W] * (2 - len(d))
    body, desc = G[ch]
    w = len(body[0])
    assert all(len(r) == w for r in body + desc), ch
    return ["." * w] * 2 + body + list(desc) + ["." * w] * (2 - len(desc))


def build(out):
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen
    U = 100
    chars = sorted(set(G) | set(COMPOSE))
    names = {c: ("space" if c == " " else f"u{ord(c):04X}") for c in chars}
    glyphs, metrics = {".notdef": None}, {".notdef": (400, 0)}
    for c in chars:
        rows = grid(c)
        assert len(rows) == 11, (c, len(rows))
        pen = TTGlyphPen(None)
        w = len(rows[0])
        for r, line in enumerate(rows):
            for k, px in enumerate(line):
                if px == "#":
                    x0, y1 = k * U, (9 - r) * U  # ligne 8 = juste au-dessus de la ligne de base
                    y0, x1 = y1 - U, x0 + U
                    pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
        glyphs[names[c]] = pen.glyph()
        metrics[names[c]] = ((w + 1) * U, 0)
    nd = TTGlyphPen(None)
    nd.moveTo((0, 0)); nd.lineTo((0, 700)); nd.lineTo((300, 700)); nd.lineTo((300, 0)); nd.closePath()
    glyphs[".notdef"] = nd.glyph()
    fb = FontBuilder(1100, isTTF=True)
    order = [".notdef"] + [names[c] for c in chars]
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(c): names[c] for c in chars})
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=900, descent=-200)
    fb.setupNameTable({"familyName": "Grimoire", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=900, sTypoDescender=-200, usWinAscent=900, usWinDescent=200)
    fb.setupPost()
    fb.font.flavor = "woff"
    fb.save(out)
    return len(chars)


def preview(text, scale=3):
    """Aperçu PNG d'un texte avec la police (pour vérifier les glyphes à l'œil)."""
    from PIL import Image
    rows_all = [grid(c) if (c in G or c in COMPOSE) else grid("?") for c in text]
    W = sum(len(r[0]) + 1 for r in rows_all)
    im = Image.new("RGB", (W * scale + 8, 11 * scale + 8), (26, 20, 36))
    x = 4
    for rows in rows_all:
        for r, line in enumerate(rows):
            for k, px in enumerate(line):
                if px == "#":
                    im.paste((242, 194, 91), (x + k * scale, 4 + r * scale, x + (k + 1) * scale, 4 + (r + 1) * scale))
        x += (len(rows[0]) + 1) * scale
    return im


